# Sayılar (data-en'i olmayan .num öğeleri): dile göre yazım
SAYI = {  # TR: (EN, RU, ES)
 "%50": ("50%", "50%", "50 %"), "%70": ("70%", "70%", "70 %"), "%100": ("100%", "100%", "100 %"),
 "30.000": ("30,000", "30 000", "30.000"), "37.000": ("37,000", "37 000", "37.000"),
 "1.000+": ("1,000+", "1 000+", "1.000+"),
}

def a(v): return html.escape(v, quote=True)

def main():
    p = os.path.join(KOK, "sunum.html")
    s = open(p, encoding="utf-8").read()
    s = re.sub(r' data-(?:ru|es)="[^"]*"', "", s)
    # önceki çalıştırmadan kalan sayı çevirilerini temizle (data-en'leri de bu araç ekledi)
    for tr in SAYI:
        s = re.sub(r'(<div class="num"(?: style="[^"]*")?) data-en="[^"]*">' + re.escape(tr) + '<', lambda m: m.group(1) + '>' + tr + '<', s)
    n = len(re.findall(r'data-en="', s))
    assert n == len(RU) == len(ES), f"sunumda {n} data-en var; RU {len(RU)}, ES {len(ES)}"
    it = iter(zip(RU, ES))
    def ekle(m):
        ru, es = next(it)
        return f'{m.group(0)} data-ru="{a(ru)}" data-es="{a(es)}"'
    s = re.sub(r'data-en="[^"]*"', ekle, s)
    for tr, (en, ru, es) in SAYI.items():
        s = re.sub(r'(<div class="num"(?: style="[^"]*")?)>' + re.escape(tr) + '<',
                   lambda m: f'{m.group(1)} data-en="{a(en)}" data-ru="{a(ru)}" data-es="{a(es)}">{tr}<', s)
    open(p, "w", encoding="utf-8").write(s)
    print("data-en:", n, "| data-ru/es eklendi | sayı öğeleri:", len(re.findall(r'class="num" data-en', s)))

if __name__ == "__main__":
    main()
